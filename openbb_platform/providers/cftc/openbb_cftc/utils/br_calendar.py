def _parse_holidays(compact: str) -> frozenset[dateType]:
    return frozenset(
        dateType(
            int(compact[i : i + 4]),
            int(compact[i + 4 : i + 6]),
            int(compact[i + 6 : i + 8]),
        )
        for i in range(0, len(compact), 8)
    )


BRL_HOLIDAYS: frozenset[dateType] = _parse_holidays(_HOLIDAYS_COMPACT)


def is_brl_business_day(day: dateType) -> bool:
    """Whether a date is a Brazilian business day."""
    return day.weekday() < 5 and day not in BRL_HOLIDAYS


def brl_business_days_between(start: dateType, end: dateType) -> int:
    """Count Brazilian business days in [start, end)."""
    if end <= start:
        return 0

    return sum(
        1
        for offset in range((end - start).days)
        if is_brl_business_day(start + timedelta(days=offset))
    )
